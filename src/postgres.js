import { randomBytes } from 'node:crypto';
import pg from 'pg';

const { Pool } = pg;
const now = () => Math.floor(Date.now() / 1000);
const first = async (pool, sql, params = []) => (await pool.query(sql, params)).rows[0];

const schema = `
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  first_name TEXT NOT NULL DEFAULT '',
  username TEXT,
  joined_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  blocked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS links (
  token TEXT PRIMARY KEY,
  owner_id TEXT NOT NULL REFERENCES users(id),
  mode TEXT NOT NULL CHECK (mode IN ('anonymous', 'open_sender')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS links_owner_idx ON links(owner_id, created_at DESC);
CREATE TABLE IF NOT EXISTS conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  link_token TEXT NOT NULL REFERENCES links(token),
  visitor_id TEXT NOT NULL REFERENCES users(id),
  created_at BIGINT NOT NULL,
  UNIQUE(link_token, visitor_id)
);
CREATE TABLE IF NOT EXISTS contexts (
  user_id TEXT PRIMARY KEY REFERENCES users(id),
  kind TEXT NOT NULL,
  target TEXT,
  updated_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS admin_drafts (
  admin_id TEXT PRIMARY KEY REFERENCES users(id),
  source_message_id BIGINT,
  button_label TEXT,
  button_url TEXT
);
CREATE TABLE IF NOT EXISTS broadcast_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_admin_id TEXT NOT NULL,
  source_message_id BIGINT NOT NULL,
  button_label TEXT,
  button_url TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at BIGINT NOT NULL,
  finished_at BIGINT
);
CREATE TABLE IF NOT EXISTS broadcast_deliveries (
  job_id BIGINT NOT NULL REFERENCES broadcast_jobs(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL CHECK (status IN ('sent', 'failed')),
  PRIMARY KEY(job_id, user_id)
);
CREATE TABLE IF NOT EXISTS broadcast_job_kinds (
  job_id BIGINT PRIMARY KEY REFERENCES broadcast_jobs(id),
  kind TEXT NOT NULL CHECK (kind IN ('announcement', 'sponsored'))
);
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS user_settings (
  user_id TEXT PRIMARY KEY REFERENCES users(id),
  login TEXT UNIQUE,
  auto_reply TEXT,
  ads_opt_in BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS user_settings_login_lower_idx
  ON user_settings(lower(login)) WHERE login IS NOT NULL;
CREATE TABLE IF NOT EXISTS personal_links (
  owner_id TEXT PRIMARY KEY REFERENCES users(id),
  link_token TEXT NOT NULL UNIQUE REFERENCES links(token)
);
CREATE TABLE IF NOT EXISTS link_visits (
  owner_id TEXT NOT NULL REFERENCES users(id),
  link_token TEXT NOT NULL REFERENCES links(token),
  visitor_id TEXT NOT NULL REFERENCES users(id),
  day BIGINT NOT NULL,
  visited_at BIGINT NOT NULL,
  PRIMARY KEY(link_token, visitor_id, day)
);
CREATE INDEX IF NOT EXISTS link_visits_owner_idx ON link_visits(owner_id, visited_at);
CREATE TABLE IF NOT EXISTS incoming_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id TEXT NOT NULL REFERENCES users(id),
  link_token TEXT NOT NULL REFERENCES links(token),
  visitor_id TEXT NOT NULL REFERENCES users(id),
  sent_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS incoming_messages_owner_idx ON incoming_messages(owner_id, sent_at);
CREATE TABLE IF NOT EXISTS blocked_conversations (
  conversation_id BIGINT PRIMARY KEY REFERENCES conversations(id),
  owner_id TEXT NOT NULL REFERENCES users(id),
  created_at BIGINT NOT NULL
);
`;

export async function openPostgres(connectionString) {
  const pool = new Pool({ connectionString, max: 5, connectionTimeoutMillis: 10000 });
  pool.on('error', (error) => console.error(`PostgreSQL ulanishi: ${error.message}`));
  try {
    await pool.query('SELECT 1');
    await pool.query(schema);
    return pool;
  } catch (error) {
    await pool.end();
    throw error;
  }
}

export function createPostgresStore(pool) {
  return {
    async upsertUser(user) {
      const time = now();
      await pool.query(`INSERT INTO users(id, first_name, username, joined_at, last_seen_at, blocked)
        VALUES ($1, $2, $3, $4, $4, FALSE)
        ON CONFLICT(id) DO UPDATE SET first_name=EXCLUDED.first_name,
          username=EXCLUDED.username, last_seen_at=EXCLUDED.last_seen_at, blocked=FALSE`,
      [String(user.id), user.first_name || '', user.username || null, time]);
    },
    getUser(id) { return first(pool, 'SELECT * FROM users WHERE id=$1', [String(id)]); },
    async createLink(ownerId, mode) {
      if (!['anonymous', 'open_sender'].includes(mode)) throw new Error('Invalid mode');
      const token = randomBytes(8).toString('hex');
      return first(pool, `INSERT INTO links(token, owner_id, mode, created_at)
        VALUES ($1, $2, $3, $4) RETURNING *`, [token, String(ownerId), mode, now()]);
    },
    getLink(token) { return first(pool, 'SELECT * FROM links WHERE token=$1', [token]); },
    async getOrCreatePersonalLink(ownerId) {
      let link = await first(pool, `SELECT l.* FROM personal_links p
        JOIN links l ON l.token=p.link_token WHERE p.owner_id=$1`, [String(ownerId)]);
      if (link?.active) return link;
      link = await this.createLink(ownerId, 'anonymous');
      await pool.query(`INSERT INTO personal_links(owner_id, link_token) VALUES ($1, $2)
        ON CONFLICT(owner_id) DO UPDATE SET link_token=EXCLUDED.link_token`,
      [String(ownerId), link.token]);
      return link;
    },
    async setPersonalLinkMode(ownerId, mode) {
      if (!['anonymous', 'open_sender'].includes(mode)) throw new Error('Invalid mode');
      const link = await this.getOrCreatePersonalLink(ownerId);
      return first(pool, 'UPDATE links SET mode=$1 WHERE token=$2 AND owner_id=$3 RETURNING *',
        [mode, link.token, String(ownerId)]);
    },
    async resolveStartParameter(parameter) {
      const directLink = await this.getLink(parameter);
      if (directLink) return directLink;
      if (parameter.startsWith('p_')) {
        const legacyLink = await first(pool, `SELECT l.* FROM user_settings s
          JOIN personal_links p ON p.owner_id=s.user_id JOIN links l ON l.token=p.link_token
          WHERE lower(s.login)=lower($1)`, [parameter.slice(2)]);
        if (legacyLink) return legacyLink;
      }
      return first(pool, `SELECT l.* FROM user_settings s
        JOIN personal_links p ON p.owner_id=s.user_id JOIN links l ON l.token=p.link_token
        WHERE lower(s.login)=lower($1)`, [parameter]);
    },
    async setLogin(userId, login) {
      const taken = await first(pool, `SELECT 1 FROM links WHERE lower(token)=lower($1)
        UNION ALL SELECT 1 FROM user_settings WHERE lower(login)=lower($1) AND user_id<>$2 LIMIT 1`,
      [login, String(userId)]);
      if (taken) {
        const error = new Error('Login is taken');
        error.code = 'LOGIN_TAKEN';
        throw error;
      }
      await pool.query(`INSERT INTO user_settings(user_id, login) VALUES ($1, $2)
        ON CONFLICT(user_id) DO UPDATE SET login=EXCLUDED.login`, [String(userId), login]);
    },
    getSettings(userId) {
      return first(pool, 'SELECT * FROM user_settings WHERE user_id=$1', [String(userId)]);
    },
    async setAutoReply(userId, text) {
      await pool.query(`INSERT INTO user_settings(user_id, auto_reply) VALUES ($1, $2)
        ON CONFLICT(user_id) DO UPDATE SET auto_reply=EXCLUDED.auto_reply`, [String(userId), text]);
    },
    async setAdsOptIn(userId, enabled) {
      await pool.query(`INSERT INTO user_settings(user_id, ads_opt_in) VALUES ($1, $2)
        ON CONFLICT(user_id) DO UPDATE SET ads_opt_in=EXCLUDED.ads_opt_in`, [String(userId), Boolean(enabled)]);
    },
    async recordVisit(ownerId, linkToken, visitorId) {
      const time = now();
      await pool.query(`INSERT INTO link_visits(owner_id, link_token, visitor_id, day, visited_at)
        VALUES ($1, $2, $3, $4, $5) ON CONFLICT DO NOTHING`,
      [String(ownerId), linkToken, String(visitorId), Math.floor(time / 86400), time]);
    },
    async recordIncomingMessage(ownerId, linkToken, visitorId) {
      await pool.query(`INSERT INTO incoming_messages(owner_id, link_token, visitor_id, sent_at)
        VALUES ($1, $2, $3, $4)`, [String(ownerId), linkToken, String(visitorId), now()]);
    },
    async profileStats(ownerId) {
      const windows = [['24 soat', 86400], ['7 kun', 604800], ['30 kun', 2592000]];
      return Promise.all(windows.map(async ([label, seconds]) => {
        const visitors = await first(pool, `SELECT COUNT(DISTINCT visitor_id) AS n FROM link_visits
          WHERE owner_id=$1 AND visited_at>=$2`, [String(ownerId), now() - seconds]);
        const messages = await first(pool, `SELECT COUNT(*) AS n FROM incoming_messages
          WHERE owner_id=$1 AND sent_at>=$2`, [String(ownerId), now() - seconds]);
        return { label, visitors: Number(visitors.n), messages: Number(messages.n) };
      }));
    },
    async blockConversation(conversationId, ownerId) {
      const conversation = await this.getConversation(conversationId);
      if (!conversation || conversation.owner_id !== String(ownerId)) return false;
      await pool.query(`INSERT INTO blocked_conversations(conversation_id, owner_id, created_at)
        VALUES ($1, $2, $3) ON CONFLICT DO NOTHING`, [conversation.id, String(ownerId), now()]);
      return true;
    },
    async unblockConversation(conversationId, ownerId) {
      const result = await pool.query(`DELETE FROM blocked_conversations
        WHERE conversation_id=$1 AND owner_id=$2`, [Number(conversationId), String(ownerId)]);
      return result.rowCount > 0;
    },
    async unblockAllConversations(ownerId) {
      const result = await pool.query('DELETE FROM blocked_conversations WHERE owner_id=$1', [String(ownerId)]);
      return result.rowCount;
    },
    async isConversationBlocked(conversationId) {
      return Boolean(await first(pool, 'SELECT 1 FROM blocked_conversations WHERE conversation_id=$1',
        [Number(conversationId)]));
    },
    async listBlockedConversations(ownerId, offset = 0, limit = 11) {
      const result = await pool.query(`SELECT c.id FROM blocked_conversations b
        JOIN conversations c ON c.id=b.conversation_id
        WHERE b.owner_id=$1 ORDER BY b.created_at DESC LIMIT $2 OFFSET $3`,
      [String(ownerId), limit, offset]);
      return result.rows;
    },
    async listLinks(ownerId, offset = 0, limit = 11) {
      const result = await pool.query(`SELECT * FROM links WHERE owner_id=$1
        ORDER BY created_at DESC, token DESC LIMIT $2 OFFSET $3`, [String(ownerId), limit, offset]);
      return result.rows;
    },
    async deactivateLink(token, ownerId) {
      const result = await pool.query('UPDATE links SET active=FALSE WHERE token=$1 AND owner_id=$2',
        [token, String(ownerId)]);
      return result.rowCount > 0;
    },
    async getOrCreateConversation(token, visitorId) {
      const existing = await first(pool, 'SELECT * FROM conversations WHERE link_token=$1 AND visitor_id=$2',
        [token, String(visitorId)]);
      if (existing) return { conversation: existing, isNew: false };
      const inserted = await first(pool, `INSERT INTO conversations(link_token, visitor_id, created_at)
        VALUES ($1, $2, $3) ON CONFLICT(link_token, visitor_id) DO NOTHING RETURNING *`,
      [token, String(visitorId), now()]);
      return { conversation: inserted || await first(pool,
        'SELECT * FROM conversations WHERE link_token=$1 AND visitor_id=$2', [token, String(visitorId)]),
      isNew: Boolean(inserted) };
    },
    getConversation(id) {
      return first(pool, `SELECT c.*, l.owner_id, l.mode, l.active FROM conversations c
        JOIN links l ON l.token=c.link_token WHERE c.id=$1`, [Number(id)]);
    },
    async setContext(userId, kind, target = null) {
      await pool.query(`INSERT INTO contexts(user_id, kind, target, updated_at) VALUES ($1, $2, $3, $4)
        ON CONFLICT(user_id) DO UPDATE SET kind=EXCLUDED.kind, target=EXCLUDED.target,
          updated_at=EXCLUDED.updated_at`,
      [String(userId), kind, target === null ? null : String(target), now()]);
    },
    getContext(userId) { return first(pool, 'SELECT * FROM contexts WHERE user_id=$1', [String(userId)]); },
    async clearContext(userId) { await pool.query('DELETE FROM contexts WHERE user_id=$1', [String(userId)]); },
    async stats() {
      const row = await first(pool, `SELECT
        (SELECT COUNT(*) FROM users) AS users,
        (SELECT COUNT(*) FROM users WHERE blocked=FALSE) AS active_users,
        (SELECT COUNT(*) FROM links WHERE active=TRUE) AS links,
        (SELECT COUNT(*) FROM conversations) AS conversations`);
      return { users: Number(row.users), activeUsers: Number(row.active_users),
        links: Number(row.links), conversations: Number(row.conversations) };
    },
    async saveDraft(adminId, messageId) {
      await pool.query(`INSERT INTO admin_drafts(admin_id, source_message_id) VALUES ($1, $2)
        ON CONFLICT(admin_id) DO UPDATE SET source_message_id=EXCLUDED.source_message_id,
          button_label=NULL, button_url=NULL`, [String(adminId), messageId]);
    },
    getDraft(adminId) { return first(pool, 'SELECT * FROM admin_drafts WHERE admin_id=$1', [String(adminId)]); },
    async setDraftButton(adminId, label, url) {
      await pool.query('UPDATE admin_drafts SET button_label=$1, button_url=$2 WHERE admin_id=$3',
        [label, url, String(adminId)]);
    },
    async clearDraft(adminId) { await pool.query('DELETE FROM admin_drafts WHERE admin_id=$1', [String(adminId)]); },
    async createBroadcast(adminId, kind = 'announcement') {
      if (!['announcement', 'sponsored'].includes(kind)) throw new Error('Invalid broadcast kind');
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const draft = (await client.query('SELECT * FROM admin_drafts WHERE admin_id=$1 FOR UPDATE',
          [String(adminId)])).rows[0];
        if (!draft?.source_message_id) {
          await client.query('ROLLBACK');
          return null;
        }
        const job = (await client.query(`INSERT INTO broadcast_jobs
          (source_admin_id, source_message_id, button_label, button_url, created_at)
          VALUES ($1, $2, $3, $4, $5) RETURNING id`,
        [String(adminId), draft.source_message_id, draft.button_label, draft.button_url, now()])).rows[0];
        await client.query('INSERT INTO broadcast_job_kinds(job_id, kind) VALUES ($1, $2)', [job.id, kind]);
        await client.query('DELETE FROM admin_drafts WHERE admin_id=$1', [String(adminId)]);
        await client.query('COMMIT');
        return Number(job.id);
      } catch (error) {
        await client.query('ROLLBACK');
        throw error;
      } finally { client.release(); }
    },
    async pendingJobs() {
      const result = await pool.query(`SELECT j.*, COALESCE(k.kind, 'announcement') AS kind
        FROM broadcast_jobs j LEFT JOIN broadcast_job_kinds k ON k.job_id=j.id
        WHERE j.status IN ('pending', 'running') ORDER BY j.id`);
      return result.rows;
    },
    nextBroadcastUser(jobId, kind = 'announcement') {
      return first(pool, `SELECT u.id FROM users u LEFT JOIN broadcast_deliveries d
        ON d.user_id=u.id AND d.job_id=$1 LEFT JOIN user_settings s ON s.user_id=u.id
        WHERE d.user_id IS NULL AND u.blocked=FALSE
        AND ($2='announcement' OR COALESCE(s.ads_opt_in,FALSE)=TRUE)
        ORDER BY u.joined_at, u.id LIMIT 1`, [jobId, kind]);
    },
    async markJobRunning(jobId) {
      await pool.query("UPDATE broadcast_jobs SET status='running' WHERE id=$1", [jobId]);
    },
    async markDelivery(jobId, userId, status) {
      await pool.query(`INSERT INTO broadcast_deliveries(job_id, user_id, status)
        VALUES ($1, $2, $3) ON CONFLICT DO NOTHING`, [jobId, String(userId), status]);
    },
    async markBlocked(userId) { await pool.query('UPDATE users SET blocked=TRUE WHERE id=$1', [String(userId)]); },
    async finishJob(jobId) {
      await pool.query("UPDATE broadcast_jobs SET status='done', finished_at=$1 WHERE id=$2", [now(), jobId]);
    },
    async jobStats(jobId) {
      const result = await pool.query(`SELECT status, COUNT(*) AS n FROM broadcast_deliveries
        WHERE job_id=$1 GROUP BY status`, [jobId]);
      return result.rows;
    },
    async getOffset() {
      const row = await first(pool, "SELECT value FROM settings WHERE key='update_offset'");
      return Number(row?.value || 0);
    },
    async setOffset(offset) {
      await pool.query(`INSERT INTO settings(key, value) VALUES ('update_offset', $1)
        ON CONFLICT(key) DO UPDATE SET value=EXCLUDED.value`, [String(offset)]);
    },
  };
}
